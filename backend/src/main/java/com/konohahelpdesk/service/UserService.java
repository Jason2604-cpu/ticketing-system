package com.konohahelpdesk.service;

import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.security.crypto.password.PasswordEncoder;

import com.konohahelpdesk.dto.CreateUserRequest;
import com.konohahelpdesk.model.UserStatus;
import com.konohahelpdesk.repository.UserRepository;
import com.konohahelpdesk.model.User;
import com.konohahelpdesk.model.Roles;

public class UserService {
    
    @Autowired
    private UserRepository userRepository;

    @Autowired
    private PasswordEncoder passwordEncoder;  // BCrypt encoder

    public User createEngineer(CreateUserRequest request) {

        User user = new User();

        // From the form
        user.setFirstName(request.getFirstName());
        user.setLastName(request.getLastName());
        user.setEmail(request.getEmail());
        user.setPhone(request.getPhone());
        user.setRole(request.getRole());

        // ── Auto-generated by backend ──────────────────

        // 1. Generate userCode e.g. "ENG-0042"
        //    Count existing users + 1, pad to 4 digits
        long count = userRepository.count() + 1;
        String userCode = request.getRole() == Roles.ADMIN
            ? String.format("ADM-%04d", count)   // ADM-0001
            : String.format("ENG-%04d", count);  // ENG-0001
        user.setUserCode(userCode);

        // 2. Generate a temporary password e.g. "Support@1234"
        //    User will be forced to change this on first login
        String tempPassword = "kanoha@" + (1000 + (int)(Math.random() * 9000));

        // 3. Hash the password with BCrypt before saving
        //    NEVER save plain text passwords
        user.setPassword(passwordEncoder.encode(tempPassword));

        // 4. Status starts as INVITED
        user.setStatus(UserStatus.INVITED);

        // Save to DB
        User savedUser = userRepository.save(user);

        // TODO: Send invite email with tempPassword to user.getEmail()
        // This is where you'd call your email service

        return savedUser;
    }
}
