-- Automation module (AUTOMATION_RULES plan feature).
--
-- automation_settings: one row per company, created lazily the first time a company's settings are
--   read or saved. A company with no row behaves as if it had the column defaults below.
--   customer_can_edit lets staff lock a company's automations so only staff can change them.
-- automation_runs: one row per (company, automation, period). The unique key is what makes the
--   scheduled sweep safe to re-run (restarts, a second replica): a period already sent is never sent again.

CREATE TABLE automation_settings (
    company_id bigint NOT NULL,
    monthly_summary_enabled boolean DEFAULT true NOT NULL,
    monthly_summary_day integer DEFAULT 1 NOT NULL,
    monthly_summary_extra_recipients character varying(1000),
    customer_can_edit boolean DEFAULT true NOT NULL,
    created_at timestamp(6) without time zone,
    updated_at timestamp(6) without time zone,
    CONSTRAINT automation_settings_pkey PRIMARY KEY (company_id),
    CONSTRAINT automation_settings_company_fk FOREIGN KEY (company_id) REFERENCES companies(id) ON DELETE CASCADE,
    CONSTRAINT automation_settings_day_check CHECK (monthly_summary_day BETWEEN 1 AND 28)
);

CREATE TABLE automation_runs (
    id bigint NOT NULL,
    company_id bigint NOT NULL,
    automation_type character varying(40) NOT NULL,
    period_key character varying(20) NOT NULL,
    status character varying(20) NOT NULL,
    recipient_count integer DEFAULT 0 NOT NULL,
    attempts integer DEFAULT 1 NOT NULL,
    detail character varying(500),
    ran_at timestamp(6) without time zone NOT NULL,
    CONSTRAINT automation_runs_pkey PRIMARY KEY (id),
    CONSTRAINT automation_runs_company_fk FOREIGN KEY (company_id) REFERENCES companies(id) ON DELETE CASCADE,
    CONSTRAINT uk_automation_run UNIQUE (company_id, automation_type, period_key)
);

ALTER TABLE automation_runs ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY (
    SEQUENCE NAME automation_runs_id_seq
    START WITH 1
    INCREMENT BY 1
    NO MINVALUE
    NO MAXVALUE
    CACHE 1
);

CREATE INDEX idx_automation_runs_company_ran ON automation_runs USING btree (company_id, ran_at DESC);
