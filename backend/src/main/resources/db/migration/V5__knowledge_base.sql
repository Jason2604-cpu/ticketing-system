-- kb_articles holds the WORKING COPY that writers edit. Readers never see it: they see the row in
-- kb_article_versions that published_version_id points at. Every publish adds an immutable version,
-- so editing a published article changes nothing for readers until an Admin / KB manager publishes
-- again. Only published versions carry a search vector, so drafts can never show up in search.

CREATE TABLE kb_categories (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        varchar(80)  NOT NULL,
    description varchar(200),
    icon        varchar(40),
    sort_order  integer      NOT NULL DEFAULT 0,
    created_at  timestamp(6) without time zone
);
CREATE UNIQUE INDEX ux_kb_categories_name ON kb_categories (lower(name));

CREATE TABLE kb_articles (
    id                      bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    slug                    varchar(160) NOT NULL,
    title                   varchar(200) NOT NULL,
    summary                 varchar(300),
    body                    text         NOT NULL,
    category_id             bigint REFERENCES kb_categories (id) ON DELETE SET NULL,
    visibility              varchar(10)  NOT NULL,
    status                  varchar(12)  NOT NULL,
    published_version_id    bigint,      -- FK added below, once kb_article_versions exists
    has_unpublished_changes boolean      NOT NULL DEFAULT false,
    publish_requested_at    timestamp(6) without time zone,
    publish_requested_by    bigint REFERENCES users (id),
    view_count              bigint       NOT NULL DEFAULT 0,
    created_by              bigint REFERENCES users (id),
    updated_by              bigint REFERENCES users (id),
    created_at              timestamp(6) without time zone,
    updated_at              timestamp(6) without time zone,
    published_at            timestamp(6) without time zone,
    CONSTRAINT kb_articles_visibility_check CHECK (visibility IN ('INTERNAL', 'PUBLIC')),
    CONSTRAINT kb_articles_status_check     CHECK (status IN ('DRAFT', 'PUBLISHED', 'ARCHIVED'))
);
CREATE UNIQUE INDEX ux_kb_articles_slug ON kb_articles (slug);
CREATE INDEX ix_kb_articles_status_updated ON kb_articles (status, updated_at DESC);
CREATE INDEX ix_kb_articles_category ON kb_articles (category_id);
-- The "Needs publishing" tab: only the handful of rows waiting for a manager are in this index.
CREATE INDEX ix_kb_articles_publish_requested ON kb_articles (publish_requested_at)
    WHERE publish_requested_at IS NOT NULL;

-- Working-copy company scope. No rows = global.
CREATE TABLE kb_article_companies (
    article_id bigint NOT NULL REFERENCES kb_articles (id) ON DELETE CASCADE,
    company_id bigint NOT NULL REFERENCES companies (id) ON DELETE CASCADE,
    PRIMARY KEY (article_id, company_id)
);
CREATE INDEX ix_kb_article_companies_company ON kb_article_companies (company_id);

-- Immutable publish history. company_ids is a snapshot of the scope at publish time ('{}' = global);
-- an array rather than a join table because it is only ever read whole, and the reader queries
-- test it with && (overlap) against the caller's companies.
CREATE TABLE kb_article_versions (
    id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    article_id   bigint       NOT NULL REFERENCES kb_articles (id) ON DELETE CASCADE,
    version      integer      NOT NULL,
    title        varchar(200) NOT NULL,
    summary      varchar(300),
    body         text         NOT NULL,
    visibility   varchar(10)  NOT NULL,
    category_id  bigint REFERENCES kb_categories (id) ON DELETE SET NULL,
    company_ids  bigint[]     NOT NULL DEFAULT '{}',
    change_note  varchar(200),
    published_by bigint REFERENCES users (id),
    published_at timestamp(6) without time zone NOT NULL,
    -- English articles: stemmed, weighted title > summary > body. Not mapped in JPA.
    search_vector tsvector GENERATED ALWAYS AS (
           setweight(to_tsvector('english'::regconfig, coalesce(title, '')),   'A')
        || setweight(to_tsvector('english'::regconfig, coalesce(summary, '')), 'B')
        || setweight(to_tsvector('english'::regconfig, coalesce(body, '')),    'C')
    ) STORED,
    CONSTRAINT kb_article_versions_visibility_check CHECK (visibility IN ('INTERNAL', 'PUBLIC')),
    CONSTRAINT ux_kb_article_versions_article_version UNIQUE (article_id, version)
);
CREATE INDEX ix_kb_versions_search ON kb_article_versions USING gin (search_vector);
CREATE INDEX ix_kb_versions_category ON kb_article_versions (category_id);

ALTER TABLE kb_articles
    ADD CONSTRAINT fk_kb_articles_published_version
    FOREIGN KEY (published_version_id) REFERENCES kb_article_versions (id) ON DELETE SET NULL;
CREATE INDEX ix_kb_articles_published_version ON kb_articles (published_version_id);

-- Articles linked from tickets (used from phase 6 on).
CREATE TABLE kb_ticket_articles (
    ticket_id  bigint NOT NULL REFERENCES tickets (id) ON DELETE CASCADE,
    article_id bigint NOT NULL REFERENCES kb_articles (id) ON DELETE CASCADE,
    linked_by  bigint REFERENCES users (id),
    linked_at  timestamp(6) without time zone NOT NULL,
    PRIMARY KEY (ticket_id, article_id)
);
CREATE INDEX ix_kb_ticket_articles_article ON kb_ticket_articles (article_id);

-- New enum values. Same pattern as V3: the CHECK lists every value, so it is replaced.
ALTER TABLE role_privileges DROP CONSTRAINT IF EXISTS role_privileges_privilege_check;
ALTER TABLE role_privileges ADD CONSTRAINT role_privileges_privilege_check
    CHECK (privilege IN ('MANAGE_USERS', 'MANAGE_COMPANIES', 'MANAGE_PLANS', 'MANAGE_ROLES',
                         'MANAGE_CONTRACTS', 'VIEW_AUDIT_LOG', 'MANAGE_TEMPLATES', 'MANAGE_ASSETS',
                         'MANAGE_KNOWLEDGE_BASE'));

ALTER TABLE media_files DROP CONSTRAINT IF EXISTS media_files_kind_check;
ALTER TABLE media_files ADD CONSTRAINT media_files_kind_check
    CHECK (kind IN ('USER_PHOTO', 'COMPANY_LOGO', 'TICKET_ATTACHMENT', 'CONTRACT_ATTACHMENT',
                    'KB_ATTACHMENT'));
